async function seed() {
  const payload = await getPayload({ config: configPromise })
  console.log("🚀 Сидирование глобала 'instruction'...")

  try {
    await payload.updateGlobal({
      slug: 'instruction',
      data: instructionData,
    })
    console.log(`✅ Инструкция успешно наполнена контентом (${instructionData.steps.length} шагов)`)
  } catch (err) {
    console.error(`❌ Ошибка при сидировании 'instruction':`, err)
  }
  process.exit(0)
}

seed()
