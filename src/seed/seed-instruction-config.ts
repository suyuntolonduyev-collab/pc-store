async function seed() {
  const payload = await getPayload({ config: configPromise })
  console.log("🚀 Сидирование глобала 'instruction-configurator'...")

  try {
    await payload.updateGlobal({
      slug: 'instruction-configurator',
      data: configInstructionData,
    })
    console.log(
      `✅ Инструкция конфигуратора обновлена: добавлено ${configInstructionData.steps.length} этапов проверки совместимости.`,
    )
  } catch (err) {
    console.error(`❌ Ошибка обновления 'instruction-configurator':`, err)
  }
  process.exit(0)
}

seed()
