export async function seedInstruction() {
  try {
    const payload = await getPayload({ config })

    console.log('🌱 Seeding instruction...')

    // Проверяем, существует ли уже инструкция
    let existingInstruction = null
    try {
      existingInstruction = await payload.findGlobal({
        slug: 'instruction',
      })
    } catch (error) {
      // Глобал не существует или пуст — это нормально
      console.log('Instruction global not found, creating new...')
    }

    const instructionData = {
      title: 'Как собрать компьютер самому? Полное руководство для начинающих',
      intro:
        'Сборка компьютера может показаться сложной задачей, но если следовать пошаговой инструкции, вы справитесь за 2-3 часа даже без опыта. В этом руководстве я расскажу всё: от подготовки инструментов до установки драйверов. Никакой магии — только практические советы, проверенные на сотнях сборок.',
      steps: instructionSteps,
    }

    let result
    if (existingInstruction && existingInstruction.id) {
      // Обновляем существующий глобал
      result = await payload.updateGlobal({
        slug: 'instruction',
        data: instructionData,
      })
      console.log('✅ Instruction updated successfully')
    } else {
      // Создаём новый глобал
      result = await payload.updateGlobal({
        slug: 'instruction',
        data: instructionData,
      })
      console.log('✅ Instruction created successfully')
    }

    console.log(`📖 Instruction contains ${result.steps?.length || 0} steps`)

    return result
  } catch (error) {
    console.error('❌ Error seeding instruction:', error)
    throw error
  }
}

// Функция для очистки инструкции (опционально)
export async function clearInstruction() {
  try {
    const payload = await getPayload({ config })

    console.log('🗑️ Clearing instruction...')

    // Payload не позволяет удалить глобал полностью, только очистить поля
    await payload.updateGlobal({
      slug: 'instruction',
      data: {
        title: '',
        intro: '',
        steps: [],
      },
    })

    console.log('✅ Instruction cleared')
  } catch (error) {
    console.error('❌ Error clearing instruction:', error)
    throw error
  }
}
